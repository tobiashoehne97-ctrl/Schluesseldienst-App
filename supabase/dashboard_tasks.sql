-- Gemeinsame Aufgabenliste fuer das Dashboard
-- Einmalig im Supabase SQL Editor ausfuehren.
create table if not exists public.app_aufgaben (
  id bigint generated by default as identity primary key,
  titel text not null,
  beschreibung text,
  status text not null default 'offen' check (status in ('offen','erledigt')),
  faellig_am date,
  zustaendig text,
  erstellt_von text,
  created_at timestamptz not null default now()
);
alter table public.app_aufgaben enable row level security;
drop policy if exists app_aufgaben_authenticated_all on public.app_aufgaben;
create policy app_aufgaben_authenticated_all
on public.app_aufgaben for all to authenticated
using (true) with check (true);
revoke all on public.app_aufgaben from anon, public;
grant select, insert, update, delete on public.app_aufgaben to authenticated;
grant usage, select on sequence public.app_aufgaben_id_seq to authenticated;
